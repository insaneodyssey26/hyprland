require("configs.colors")
require("configs.env")
require("configs.monitors")
require("configs.settings")
require("configs.binds")
require("configs.autostart")

hl.config({
    autogenerated = false
})

-- Vertical Workspace Swipe (Natural up/down switching with 3 fingers)
hl.gesture({
    fingers = 3,
    direction = "vertical",
    action = "workspace"
})

-- Horizontal Window/Column Swipe (Scroll columns horizontally with 3 fingers)
hl.gesture({
    fingers = 3,
    direction = "left",
    action = function()
        hl.dispatch(hl.dsp.exec_cmd("~/.config/hypr/scripts/layout_navigate.sh focus_right"))
    end
})

hl.gesture({
    fingers = 3,
    direction = "right",
    action = function()
        hl.dispatch(hl.dsp.exec_cmd("~/.config/hypr/scripts/layout_navigate.sh focus_left"))
    end
})
